import random

# -----------------------------
# Job Scheduling using Genetic Algorithm
# -----------------------------

# Processing time of each job
jobs = [4, 2, 7, 3, 5, 6, 2, 8]

# Number of machines
num_machines = 3

# Genetic Algorithm parameters
population_size = 10
generations = 50
mutation_rate = 0.1


# Create a random chromosome
# Each gene represents the machine assigned to a job
def create_chromosome():
    return [random.randint(0, num_machines - 1)
            for _ in jobs]


# Calculate fitness (lower makespan is better)
def fitness(chromosome):
    machine_times = [0] * num_machines

    for job_index, machine in enumerate(chromosome):
        machine_times[machine] += jobs[job_index]

    makespan = max(machine_times)

    # Higher fitness means a better solution
    return 1 / makespan


# Select the better parent using tournament selection
def selection(population):
    candidates = random.sample(population, 3)
    return max(candidates, key=fitness)


# Combine two parents to create a child
def crossover(parent1, parent2):
    point = random.randint(1, len(jobs) - 1)

    child = parent1[:point] + parent2[point:]
    return child


# Randomly change a job's assigned machine
def mutation(chromosome):
    chromosome = chromosome.copy()

    if random.random() < mutation_rate:
        index = random.randint(0, len(jobs) - 1)
        chromosome[index] = random.randint(
            0, num_machines - 1
        )

    return chromosome


# Initialize the population
population = [
    create_chromosome()
    for _ in range(population_size)
]

# Run the Genetic Algorithm
for generation in range(generations):

    # Keep the best solution (elitism)
    best = max(population, key=fitness)

    new_population = [best.copy()]

    while len(new_population) < population_size:
        parent1 = selection(population)
        parent2 = selection(population)

        child = crossover(parent1, parent2)
        child = mutation(child)

        new_population.append(child)

    population = new_population

# Get the best schedule
best_solution = max(population, key=fitness)

# Calculate machine workloads
machine_times = [0] * num_machines

for job_index, machine in enumerate(best_solution):
    machine_times[machine] += jobs[job_index]

# Display results
print("Best Job Schedule:")

for machine in range(num_machines):
    assigned_jobs = [
        f"J{i + 1}"
        for i, assigned_machine in enumerate(best_solution)
        if assigned_machine == machine
    ]

    print(f"Machine {machine + 1}: {assigned_jobs}")
    print(f"Total processing time: {machine_times[machine]}")

print("\nMinimum Makespan:", max(machine_times))