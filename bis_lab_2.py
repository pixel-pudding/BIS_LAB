import numpy as np

# XOR dataset
X = np.array([[0, 0],
              [0, 1],
              [1, 0],
              [1, 1]])

y = np.array([[0], [1], [1], [0]])

# Neural network: 2 inputs, 4 hidden neurons, 1 output
n_inputs = 2
n_hidden = 4
n_outputs = 1

# Total parameters: weights and biases
n_params = (n_inputs * n_hidden + n_hidden
            + n_hidden * n_outputs + n_outputs)

def sigmoid(x):
    x = np.clip(x, -500, 500)
    return 1 / (1 + np.exp(-x))

# Neural network prediction
def predict(params, X):
    i = 0

    W1 = params[i:i + n_inputs*n_hidden].reshape(
        n_inputs, n_hidden)
    i += n_inputs*n_hidden

    b1 = params[i:i + n_hidden]
    i += n_hidden

    W2 = params[i:i + n_hidden*n_outputs].reshape(
        n_hidden, n_outputs)
    i += n_hidden*n_outputs

    b2 = params[i:i + n_outputs]

    hidden = sigmoid(X @ W1 + b1)
    output = sigmoid(hidden @ W2 + b2)

    return output

# Objective function: mean squared error
def fitness(params):
    output = predict(params, X)
    return np.mean((y - output) ** 2)

# PSO settings
n_particles = 40
n_iterations = 1000
w = 0.7       # Inertia weight
c1 = 1.5      # Personal learning
c2 = 1.5      # Social learning

# Initialize particles and velocities
positions = np.random.uniform(-4, 4,
                              (n_particles, n_params))
velocities = np.zeros_like(positions)

# Initial personal and global bests
pbest = positions.copy()
pbest_scores = np.array([fitness(p) for p in positions])

best_index = np.argmin(pbest_scores)
gbest = pbest[best_index].copy()
gbest_score = pbest_scores[best_index]

# PSO optimization loop
for iteration in range(n_iterations):

    r1 = np.random.rand(n_particles, n_params)
    r2 = np.random.rand(n_particles, n_params)

    velocities = (
        w * velocities
        + c1 * r1 * (pbest - positions)
        + c2 * r2 * (gbest - positions)
    )

    positions += velocities

    # Evaluate each particle
    scores = np.array([fitness(p) for p in positions])

    # Update personal bests
    improved = scores < pbest_scores
    pbest[improved] = positions[improved]
    pbest_scores[improved] = scores[improved]

    # Update global best
    best_index = np.argmin(pbest_scores)

    if pbest_scores[best_index] < gbest_score:
        gbest = pbest[best_index].copy()
        gbest_score = pbest_scores[best_index]

    if (iteration + 1) % 100 == 0:
        print(f"Iteration {iteration+1}, "
              f"Best loss = {gbest_score:.6f}")

# Final results
print("\nFinal predictions:")
predictions = predict(gbest, X)
print(np.round(predictions, 3))

print("\nPredicted XOR classes:")
print((predictions >= 0.5).astype(int))